#!/usr/bin/env bash
# Build Summary.html from FastQC zips and STAR/RSEM outputs (bash + awk + unzip only).
set -euo pipefail
VERSION="0.1.0"

usage() {
cat <<'USAGE'
Usage: summaryHTML.sh [options] <fastqc_dir> <rsem_star_dir> <outdir>

Write <outdir>/Summary.html: Read Quality Summary (one row per FASTQ file: FastQC module
status) and Mapping Statistics (one row per sample: STAR Log.final.out and RSEM expected
counts of rRNA-biotype genes). The layout follows ref/Summary.html.

Arguments:
  fastqc_dir      directory with *_fastqc.zip
  rsem_star_dir   directory with <sample>.log (STAR Log.final.out) and <sample>.genes.results,
                  flat or in one sub-directory per sample (in the pipeline: the staged rsem/ task inputs)
  outdir          output directory (created)
Options:
  --annotation FILE     annotation TSV (gene_id, gene_name, gene_biotype); rRNA reads are the
                        expected counts of genes with biotype rRNA, Mt_rRNA or rRNA_pseudogene.
                        Without it, or without any biotype, the rRNA column shows NA
  --sample_order FILE   one sample name per line, row order (default: alphabetical)
  --single-end          reads are single-end (default: paired-end, counts are fragments)
  --info FILE           optional "Run info" table, lines of "key: value"
  --warnings FILE       optional "Validation warnings", one per line (section only if not empty)
  --fastqc_link PATH    link target of the FastQC folder (default: fastqc/)
  --footer TEXT         footer text (default: "Generated by nf-rnaseq on <date>")
  -h, --help            show this help and exit 0
  --version             print the version and exit 0

Columns of Mapping Statistics: Library | Total Reads | Uniquely Mapped | Multi-reads |
Unmapped Reads | rRNA Reads. Total Reads is an integer, the others are "N(P.PP%)" with
P = N / Total * 100. Uniquely mapped + multi + unmapped = total.

Exit codes: 0 ok, 1 missing or unreadable inputs, 2 usage error.

Example:
  summaryHTML.sh --annotation annotation.tsv fastqc/ rsem/ .
USAGE
}

die() { echo "ERROR: $*" >&2; exit 1; }
usage_error() { echo "ERROR: $*" >&2; echo >&2; usage >&2; exit 2; }
esc() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' -e 's/"/\&quot;/g'; }

ANNOT=""; ORDER=""; SE=0; INFO=""; WARN=""; FQLINK="fastqc/"; FOOTER=""
POS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help) usage; exit 0 ;;
        --version) echo "summaryHTML.sh $VERSION"; exit 0 ;;
        --single-end) SE=1; shift ;;
        --annotation|--sample_order|--info|--warnings|--fastqc_link|--footer)
            [[ $# -ge 2 ]] || usage_error "missing value for $1"
            case "$1" in
                --annotation) ANNOT="$2" ;; --sample_order) ORDER="$2" ;; --info) INFO="$2" ;;
                --warnings) WARN="$2" ;; --fastqc_link) FQLINK="$2" ;; --footer) FOOTER="$2" ;;
            esac
            shift 2 ;;
        -*) usage_error "unknown option: $1" ;;
        *) POS+=("$1"); shift ;;
    esac
done
[[ ${#POS[@]} -eq 3 ]] || usage_error "expected 3 arguments: fastqc_dir rsem_star_dir outdir"
FQDIR="${POS[0]}"; RDIR="${POS[1]}"; OUT="${POS[2]}"
[[ -d "$FQDIR" ]] || die "fastqc_dir not found: $FQDIR"
[[ -d "$RDIR" ]] || die "rsem_star_dir not found: $RDIR"
[[ -z "$ANNOT" || -r "$ANNOT" ]] || die "annotation not readable: $ANNOT"
command -v unzip >/dev/null || die "unzip is required"
mkdir -p "$OUT"
[[ -n "$FOOTER" ]] || FOOTER="Generated by nf-rnaseq on $(date +%Y-%m-%d)"

# ---------------------------------------------------------------- Read Quality Summary
FQROWS=""
shopt -s nullglob
zips=("$FQDIR"/*_fastqc.zip)
[[ ${#zips[@]} -gt 0 ]] || die "no *_fastqc.zip in $FQDIR"
for z in "${zips[@]}"; do
    base="$(basename "$z" .zip)"
    label="${base%_fastqc}"
    cells="$(unzip -p "$z" "$base/summary.txt" 2>/dev/null | awk -F'\t' '
        $2 == "Per tile sequence quality" { next }
        { st = $1; cls = (st == "PASS") ? "pass" : (st == "WARN") ? "warn" : "fail";
          printf "<td class=\"%s\">%s</td>", cls, st; n++ }
        END { if (n != 10) exit 3 }')" || die "cannot read the 10 FastQC modules from $z"
    FQROWS+="<tr><td>$(printf '%s' "$label" | esc)</td>${cells}</tr>"$'\n'
done

# ---------------------------------------------------------------- Mapping Statistics
if [[ -n "$ORDER" ]]; then
    [[ -r "$ORDER" ]] || die "sample_order not readable: $ORDER"
    samples=()
    while IFS= read -r line; do [[ -n "$line" ]] && samples+=("$line"); done < "$ORDER"
else
    samples=()
    while IFS= read -r f; do samples+=("$(basename "$f" .log)"); done < <(find "$RDIR" -maxdepth 2 -name '*.log' | sort)
fi
[[ ${#samples[@]} -gt 0 ]] || die "no STAR <sample>.log found in $RDIR"

MAPROWS=""
for s in "${samples[@]}"; do
    log="$(find "$RDIR" -maxdepth 2 -name "$s.log" | head -n 1)"
    genes="$(find "$RDIR" -maxdepth 2 -name "$s.genes.results" | head -n 1)"
    [[ -n "$log" ]] || die "STAR log for sample $s not found in $RDIR"
    [[ -n "$genes" ]] || die "genes.results for sample $s not found in $RDIR"
    row="$(awk -v sample="$s" -v annot="$ANNOT" -v genes="$genes" -F'|' '
        function trim(x) { gsub(/^[ \t]+|[ \t]+$/, "", x); return x }
        function cell(n, tot) { return sprintf("<td>%.0f(%.2f%%)</td>", n, tot > 0 ? 100 * n / tot : 0) }
        { k = trim($1); v = trim($2) }
        k == "Number of input reads"                        { total = v }
        k == "Uniquely mapped reads number"                 { uniq = v }
        k == "Number of reads mapped to multiple loci"      { multi += v }
        k == "Number of reads mapped to too many loci"      { multi += v }
        k ~ /^Number of reads unmapped:/                    { unm += v }
        END {
            if (total == "" || uniq == "") { print "ERR"; exit 3 }
            # rRNA reads: expected counts of rRNA-biotype genes
            rr = "<td>NA</td>"
            if (annot != "") {
                FS_SAVE = FS
                while ((getline line < annot) > 0) {
                    split(line, a, "\t")
                    if (a[3] != "NA" && a[3] != "gene_biotype") hasbio = 1
                    if (a[3] ~ /^(rRNA|Mt_rRNA|rRNA_pseudogene)$/) isr[a[1]] = 1
                }
                close(annot)
                if (hasbio) {
                    ecol = 0
                    while ((getline line < genes) > 0) {
                        split(line, g, "\t")
                        if (!ecol) { for (i in g) if (g[i] == "expected_count") ecol = i; continue }
                        if (g[1] in isr) rsum += g[ecol]
                    }
                    close(genes)
                    rr = cell(rsum, total)
                }
            }
            printf "<tr><td>%s</td><td>%.0f</td>%s%s%s%s</tr>\n", sample, total, cell(uniq, total), cell(multi, total), cell(unm, total), rr
            if (uniq + multi + unm != total) printf "WARNING: %s: unique+multi+unmapped (%.0f) != total (%.0f)\n", sample, uniq + multi + unm, total > "/dev/stderr"
        }' "$log")" || die "cannot parse STAR log: $log"
    [[ "$row" != "ERR" ]] || die "STAR log lacks the expected fields: $log"
    MAPROWS+="$row"$'\n'
done

if [[ $SE -eq 1 ]]; then
    NOTE="Single-end data: counts are reads."
else
    NOTE="Paired-end data: counts are fragments (read pairs)."
fi

# ---------------------------------------------------------------- optional sections
EXTRA=""
if [[ -n "$INFO" && -s "$INFO" ]]; then
    EXTRA+='<div class="module"><h2 id="M2">Run info</h2></div>'$'\n<table>\n<tbody>\n'
    while IFS= read -r line; do
        [[ -n "$line" ]] || continue
        k="${line%%:*}"; v="${line#*:}"; v="${v# }"
        EXTRA+="<tr><td>$(printf '%s' "$k" | esc)</td><td>$(printf '%s' "$v" | esc)</td></tr>"$'\n'
    done < "$INFO"
    EXTRA+=$'</tbody>\n</table>\n'
fi
if [[ -n "$WARN" && -s "$WARN" ]]; then
    EXTRA+='<div class="module"><h2 id="M3">Validation warnings</h2></div>'$'\n<ul>\n'
    while IFS= read -r line; do
        [[ -n "$line" ]] && EXTRA+="<li>$(printf '%s' "$line" | esc)</li>"$'\n'
    done < "$WARN"
    EXTRA+=$'</ul>\n'
fi

# ---------------------------------------------------------------- write
TITLE="Summary Report"
{
cat <<EOF
<html>
<head><title>$TITLE</title>
</head>
<style type="text/css">
div.main {
background-color: white;
}

div.module {
padding-bottom:0.5em;
padding-top:1.0em;
}

div.footer {
padding-top:2.0em;
padding-bottom:2.0em;
overflow:hidden;
border-bottom: 5.0em;
}

img.indented {
margin-left: 3em;
}

table {
margin-left: 3em;
text-align: left;
}

th {
text-align: center;
background-color: #000080;
color: #FFF;
padding: 0.4em;
}

td {
font-family: monospace;
text-align: left;
background-color: #EEE;
color: #000;
padding: 0.4em;
padding-right: 0.8em;
padding-left: 0.8em;
}

td.pass { background-color: #c6e8c6; }
td.warn { background-color: #ffe08a; }
td.fail { background-color: #f4a6a6; }

img {
padding-top: 0;
margin-top: 0;
border-top: 0;
}

p {
padding-top: 0;
margin-top: 0;
}
</style>

<body>
<h1>$TITLE</h1>
<div class="module"><h2 id="M0">Read Quality Summary</h2></div>
<p style="margin-left:3em">See <a href="$(printf '%s' "$FQLINK" | esc)">$(printf '%s' "$FQLINK" | esc)</a> for the full FastQC reports.</p>
<table>
<thead><tr><th>Library</th><th>Basic Statistics</th><th>Per base quality</th><th>Per sequence quality scores</th><th>Per base sequence content</th><th>Per sequence GC content</th><th>Per base N content</th><th>Sequence Length Distribution</th><th>Sequence Duplication Levels</th><th>Overrepresented sequences</th><th>Adapter Content</th></tr>
</thead>
<tbody>
EOF
printf '%s' "$FQROWS"
cat <<EOF
</tbody>
</table>

<div class="module"><h2 id="M1">Mapping Statistics</h2></div>
<table>
<thead><tr><th>Library</th><th>Total Reads</th><th>Uniquely Mapped</th><th>Multi-reads</th><th>Unmapped Reads</th><th>rRNA Reads</th></tr>
</thead>
<tbody>
EOF
printf '%s' "$MAPROWS"
cat <<EOF
</tbody>
</table>
<p style="margin-left:3em">$NOTE rRNA reads: RSEM expected counts of genes with biotype rRNA, Mt_rRNA or rRNA_pseudogene (NA without annotation biotypes).</p>

$EXTRA
<div class="footer">$(printf '%s' "$FOOTER" | esc)</div>
</body>
</html>
EOF
} > "$OUT/Summary.html"
echo "wrote $OUT/Summary.html (${#zips[@]} FASTQ reports, ${#samples[@]} samples)"
