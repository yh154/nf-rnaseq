#!/usr/bin/env python3
"""Resolve BioContainers tags to sha256 digests and (re)write conf/containers.config."""
import json
import os
import sys
import urllib.error
import urllib.request

VERSION = "0.1.0"
HELP = """\
Usage: pin_containers.py [--write | --check]

Containers are public BioContainers images (quay.io/biocontainers). The tag table below
is the single source; conf/containers.config holds the digest-pinned references that
Docker and Apptainer both use (repo@sha256:..., the tag is kept in a comment).

  --write    resolve every tag on quay.io and rewrite conf/containers.config
  --check    resolve every tag and fail (exit 1) if conf/containers.config differs
             (detects a moved tag or a hand edit); needs network access to quay.io
  -h, --help / --version

To update a tool: edit its tag in IMAGES, run --write, run tests/run_tests.sh.
"""

REGISTRY = "quay.io/biocontainers"
# label -> (repository, tag, tools / used by)
IMAGES = {
    "fastqc":    ("fastqc", "0.12.1--hdfd78af_0", "FastQC"),
    "star_rsem": ("mulled-v2-cf0123ef83b3c38c13e3b0696a3f285d3f20f15b",
                  "64aad4a4e144878400649e71f42105311be7ed87-0", "STAR 2.7.10a + RSEM 1.3.3 + samtools 1.15 (mulled)"),
    "python":    ("python", "3.12.12", "validation, annotation, expression tables"),
    "deseq2":    ("bioconductor-deseq2", "1.50.2--r45ha27e39d_0", "DESeq2 + plots (ggplot2)"),
    "fgsea":     ("bioconductor-fgsea", "1.36.2--r45ha27e39d_0", "GSEA"),
    "gsva":      ("bioconductor-gsva", "2.4.9--r45h262fe30_0", "GSVA"),
}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG = os.path.join(ROOT, "conf", "containers.config")


def digest(repo, tag):
    url = "https://quay.io/api/v1/repository/biocontainers/%s/tag/?specificTag=%s&onlyActiveTags=true" % (repo, tag)
    with urllib.request.urlopen(url, timeout=40) as r:
        tags = json.load(r).get("tags", [])
    if not tags:
        raise SystemExit("ERROR: tag not found on quay.io: %s:%s" % (repo, tag))
    return tags[0]["manifest_digest"]


def render():
    lines = [
        "// GENERATED by tools/pin_containers.py - do not edit by hand.",
        "// Public BioContainers images, pinned by sha256 digest (the tag is in the comment).",
        "// Identical references are used by -profile docker and -profile apptainer.",
        "process {",
    ]
    for label, (repo, tag, what) in IMAGES.items():
        lines.append("    // %s: %s:%s  (%s)" % (label, repo, tag, what))
        lines.append("    withLabel: %s { container = '%s/%s@%s' }" % (label, REGISTRY, repo, digest(repo, tag)))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(HELP)
        return 0 if argv else 2
    if argv[0] == "--version":
        print("pin_containers.py " + VERSION)
        return 0
    if argv[0] not in ("--write", "--check"):
        sys.stderr.write("Usage: pin_containers.py [--write | --check]\n")
        return 2
    try:
        new = render()
    except urllib.error.URLError as exc:
        sys.stderr.write("ERROR: cannot reach quay.io (%s)\n" % exc)
        return 1
    if argv[0] == "--write":
        with open(CONFIG, "w") as fh:
            fh.write(new)
        print("wrote " + CONFIG)
        return 0
    with open(CONFIG) as fh:
        old = fh.read()
    if old != new:
        sys.stderr.write("ERROR: conf/containers.config is out of date; run --write\n")
        return 1
    print("containers.config matches quay.io")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
